test('enabled activation forwards original native events once and updates the boolean model', async ({ page }) => {
	await box(page, 'Slot label').click()
	await expect(page.getByTestId('checked')).toHaveText('true')
	await expect(subject(page)).toBeChecked()
	expect((await events(page)).filter(value => value !== 'focus')).toEqual(['click:true:true', 'input:true:true', 'change:true:true', 'model:true'])
	await page.getByRole('button', { name: 'Clear events' }).click()
	await page.getByText('Slot label').click()
	await expect(page.getByTestId('checked')).toHaveText('false')
	await subject(page).press('Space')
	await expect(page.getByTestId('checked')).toHaveText('true')
	await subject(page).press('a')
	const recorded = await events(page)
	expect(recorded.filter(value => value.startsWith('input:'))).toEqual(['input:true:true', 'input:true:true'])
	expect(recorded.filter(value => value.startsWith('change:'))).toEqual(['change:true:true', 'change:true:true'])
	expect(recorded).toContain('key-a:true:true')
	await page.getByText('External name').click()
	await expect(page.getByTestId('checked')).toHaveText('false')
})

for (const initial of ['unchecked', 'checked']) {
	test(`disabled ${initial} checkbox stays focusable and blocks every activation and implicit submission`, async ({ page }) => {
		if (initial === 'checked') await page.getByRole('button', { name: 'Update models' }).click()
		const expected = initial === 'checked' ? 'true' : 'false'
		await subject(page).focus()
		await page.getByRole('button', { name: 'Toggle disabled' }).click()
		const control = subject(page)
		await expect(control).toBeFocused()
		await expect(control).toHaveAttribute('aria-disabled', 'true')
		await expect(control).not.toHaveAttribute('disabled')
		await page.getByRole('button', { name: 'Clear events' }).click()
		await box(page, 'Slot label').click({ force: true })
		await page.getByText('Slot label').click({ force: true })
		await page.getByText('External name').click({ force: true })
		await control.click({ force: true })
		await control.focus()
		await control.press('Space')
		await control.press('Enter')
		await control.evaluate(el => (el as HTMLInputElement).click())
		await expect(page.getByTestId('checked')).toHaveText(expected)
		await expect(control).toBeChecked({ checked: initial === 'checked' })
		expect((await events(page)).filter(value => /^(input|change):/.test(value))).toEqual([])
		await expect(page.getByTestId('submits')).toHaveText('0')
		await page.getByRole('button', { name: 'Update models' }).click()
		await expect(control).toBeChecked({ checked: initial !== 'checked' })
		await page.getByRole('button', { name: 'Toggle disabled' }).click()
		await control.focus()
		await control.press('Space')
		await expect(control).toBeChecked({ checked: initial === 'checked' })
		await page.getByRole('textbox', { name: 'Enabled submit' }).fill('ready')
		await page.getByRole('textbox', { name: 'Enabled submit' }).press('Enter')
		await expect(page.getByTestId('submits')).toHaveText('1')
	})
}

test('a disabled toggle that bypasses the click guard is reverted without forwarding events', async ({ page }) => {
	await page.getByRole('button', { name: 'Toggle disabled' }).click()
	await page.evaluate(() => document.addEventListener('click', event => {
		if ((event.target as Element).id === 'subject') event.stopPropagation()
	}, { capture: true }))
	await page.getByRole('button', { name: 'Clear events' }).click()
	await subject(page).evaluate(el => (el as HTMLInputElement).click())
	await expect(subject(page)).not.toBeChecked()
	await expect(page.getByTestId('checked')).toHaveText('false')
	expect(await events(page)).toEqual([])
})

