test('source SSR hydrates unique stable checkbox IDs and associations', async ({ page, request, pageLog }) => {
	const response = await request.get('/ssr-checkboxes?ssr')
	expect(response.ok()).toBeTruthy()
	const html = await response.text()
	const serverIds = [...html.matchAll(/<input[^>]*\bid="([^"]+)"/g)].map(match => match[1])
	expect(serverIds).toHaveLength(3)
	expect(new Set(serverIds).size).toBe(3)
	await page.goto('/ssr-checkboxes?ssr')
	expect(await page.locator('input').evaluateAll(nodes => nodes.map(node => node.id))).toEqual(serverIds)
	expect(pageLog.matching(/hydration|mismatch/i)).toEqual([])
	await expect(page.getByRole('checkbox', { name: 'First' })).toBeChecked()
	await expect(page.getByRole('checkbox', { name: 'First' })).toHaveAccessibleDescription('Checkbox note')
	await expect(page.getByRole('checkbox', { name: 'Second' })).toBeVisible()
	await expect(page.getByRole('checkbox', { name: 'Third' })).toHaveAttribute('aria-disabled', 'true')
	await page.getByRole('checkbox', { name: 'Second' }).check()
	await expect(page.getByRole('checkbox', { name: 'Second' })).toBeChecked()
})

test.describe('forced colours', () => {
	test.use({ forcedColors: 'active' })

	test('disabled state stays distinguishable and focus remains visible', async ({ page }) => {
		expect(await page.evaluate(() => matchMedia('(forced-colors: active)').matches)).toBe(true) // setup evidence only
		const colour = (name: string) => page.locator('.bunt-checkbox').filter({ has: page.getByRole('checkbox', { name }) }).locator('label').evaluate(node => getComputedStyle(node).color)
		expect(await colour('Checked disabled')).not.toBe(await colour('Slot label'))
		const enabledBox = box(page, 'Slot label')
		expect(await enabledBox.evaluate(el => getComputedStyle(el).getPropertyValue('forced-color-adjust'))).not.toBe('none')
		await page.getByRole('button', { name: 'Clear events' }).focus()
		await page.keyboard.press('Tab')
		expect(await enabledBox.evaluate(node => getComputedStyle(node).outlineStyle)).toBe('solid')
		const glyph = (name: string) => box(page, name).locator('.mdi')
		await expect(glyph('Slot label')).toHaveCSS('opacity', '0')
		await page.getByRole('button', { name: 'Update models' }).click()
		await expect(glyph('Slot label')).toHaveCSS('opacity', '1')
		const [glyphColour, boxBackground] = await glyph('Slot label').evaluate(node => [getComputedStyle(node).color, getComputedStyle(node.parentElement).backgroundColor])
		expect(glyphColour).not.toBe(boxBackground)
	})
})
